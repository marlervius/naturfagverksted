// t(x, lang[, vars]): x er en STRINGS-nøkkel, en vanlig streng eller et {enkel, fag}-objekt.
// Valgfritt vars-objekt fyller inn plassholdere som {name}, {a}, {b}, {n}, {max}.
export function t(x, lang, vars) {
  let s;
  if (x == null) s = '';
  else if (typeof x === 'string') s = STRINGS[x] ? t(STRINGS[x], lang) : x;
  else if (typeof x === 'object') s = x[lang] ?? x.enkel ?? x.fag ?? '';
  else s = String(x);
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (vars[k] !== undefined ? String(vars[k]) : m));
  return s;
}
