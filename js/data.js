export const ELEMENTS = RAW.map(([z, sym, name, group, shells, category, en, mass, color, size]) => {
  const b = BUILD[sym];
  return {
    z, sym, name, group,
    period: shells.length,
    shells,
    valence: MAIN_GROUPS.includes(group) ? shells[shells.length - 1] : null,
    bonds: b ? b[1] : null,
    role: b ? b[0] : null,
    buildable: !!b,
    category, en, mass, color, size,
  };
});

